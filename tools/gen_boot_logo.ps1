# Embeds the ROADWORKS mark (branding\logo_mark_512.png, scaled to 256 px) into src\boot_logo.h for the boot animation.
# Usage: powershell -ExecutionPolicy Bypass -File tools\gen_boot_logo.ps1 [-Png <file>]
param([string]$Png = (Join-Path (Split-Path (Split-Path $PSScriptRoot)) "branding\logo_mark_512.png"))
$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing
$srcImg = [System.Drawing.Image]::FromFile($Png)
$bmp = New-Object System.Drawing.Bitmap 256, 256, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$gfx = [System.Drawing.Graphics]::FromImage($bmp); $gfx.InterpolationMode = 'HighQualityBicubic'; $gfx.PixelOffsetMode = 'HighQuality'
$gfx.Clear([System.Drawing.Color]::Transparent); $gfx.DrawImage($srcImg, 0, 0, 256, 256); $gfx.Dispose(); $srcImg.Dispose()
$ms = New-Object IO.MemoryStream; $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png); $bmp.Dispose(); $bytes = $ms.ToArray()
$sb = New-Object Text.StringBuilder
[void]$sb.Append("#pragma once`n// Generated by tools/gen_boot_logo.ps1 from branding/logo_mark_512.png - do not edit.`n#include <cstddef>`n`nnamespace ep {`ninline constexpr unsigned char kBootLogoPng[] = {")
for ($q = 0; $q -lt $bytes.Length; $q++) { if ($q % 24 -eq 0) { [void]$sb.Append("`n    ") }; [void]$sb.Append(("0x{0:X2}," -f $bytes[$q])) }
[void]$sb.Append("`n};`ninline constexpr size_t kBootLogoPngSize = sizeof(kBootLogoPng);`n}  // namespace ep`n")
$outFile = Join-Path (Split-Path $PSScriptRoot) "src\boot_logo.h"
[IO.File]::WriteAllText($outFile, $sb.ToString().Replace("`n", "`r`n"), (New-Object Text.UTF8Encoding $false))
Write-Host "boot_logo.h: $($bytes.Length) bytes PNG"